"""Build a source-first research plan for P1-E lint -> research orchestration.

This script does not call search APIs or write Feishu. It turns research tasks
into a source strategy that can be executed by Claude/Codex with Google search,
manual URLs, or Tavily when quota is available.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime
from pathlib import Path
from typing import Any


SOURCE_TIERS = [
    {
        "tier": "feishu_public_knowledge",
        "label": "主来源：飞书公共知识库",
        "priority": 0,
        "role": "优先检索真实飞书公共知识库沉淀，作为草稿骨架来源。",
        "backend": "Google: site:docs.feishu.cn",
    },
    {
        "tier": "official_sources",
        "label": "官方依据",
        "priority": 1,
        "role": "补足平台规则、产品能力、API/权限边界。",
        "backend": "Google official-site queries",
    },
    {
        "tier": "industry_cases",
        "label": "行业与案例补充",
        "priority": 2,
        "role": "补充行业语境、案例、趋势和可执行 SOP。",
        "backend": "Google broad queries",
    },
    {
        "tier": "tavily_optional",
        "label": "可选聚合来源：Tavily",
        "priority": 3,
        "role": "仅在有 API 额度时启用；没有额度时直接跳过。",
        "backend": "Tavily API optional",
    },
    {
        "tier": "manual_urls",
        "label": "手工指定来源",
        "priority": 4,
        "role": "用户直接给出的 URL 必须纳入候选来源。",
        "backend": "Manual URLs",
    },
]

SCORING_DIMENSIONS = [
    "来源权重：docs.feishu.cn > 官方文档 > 行业资料 > Tavily 泛搜",
    "时效性：2026/2025 优先；无日期可用但降权",
    "可执行性：有步骤、表格、SOP、案例的内容优先",
    "信息密度：包含具体字段、流程、判断标准的内容优先",
    "独特性：真实经验沉淀优先，泛 SEO 文降权",
    "主题贴合：与 topic、research_question、supporting_evidence 越贴合越优先",
]


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Build prioritized source-search plans for lark-knowledge research tasks."
    )
    parser.add_argument(
        "--tasks-json",
        type=Path,
        help="Path to research task JSON generated by blank_identifier.py. If omitted, read stdin.",
    )
    parser.add_argument("--json-out", type=Path, help="Optional output path for source plan JSON.")
    parser.add_argument("--markdown-out", type=Path, help="Optional output path for source plan Markdown.")
    parser.add_argument(
        "--manual-url",
        action="append",
        default=[],
        help="Manual URL to include as a required candidate source. Can be used multiple times.",
    )
    parser.add_argument(
        "--max-tasks",
        type=int,
        default=5,
        help="Maximum tasks to include in the source plan. Default: 5.",
    )
    return parser.parse_args(argv)


def fail(message: str) -> "NoReturn":
    print(message, file=sys.stderr)
    raise SystemExit(1)


def load_tasks(path: Path | None) -> dict[str, Any]:
    try:
        raw = path.read_text(encoding="utf-8") if path else sys.stdin.read()
    except OSError as exc:
        fail(f"读取研究任务 JSON 失败: {exc}")
    if not raw.strip():
        fail("未提供研究任务 JSON。请传入 --tasks-json 或通过 stdin 输入。")
    try:
        payload = json.loads(raw)
    except json.JSONDecodeError as exc:
        fail(f"研究任务 JSON 解析失败: {exc}")
    if not isinstance(payload, dict) or not isinstance(payload.get("tasks"), list):
        fail("研究任务 JSON 必须包含 tasks 数组。")
    return payload


def compact(value: Any) -> str:
    if isinstance(value, str):
        return " ".join(value.split())
    if isinstance(value, list):
        return " ".join(compact(item) for item in value if compact(item))
    if value is None:
        return ""
    return " ".join(str(value).split())


def dedupe(items: list[str]) -> list[str]:
    seen: set[str] = set()
    result: list[str] = []
    for item in items:
        normalized = " ".join(item.split())
        if not normalized or normalized in seen:
            continue
        seen.add(normalized)
        result.append(normalized)
    return result


def build_queries(topic: str, question: str, evidence: str) -> dict[str, list[str]]:
    base = topic.strip()
    context = f"{topic} {question}".strip()
    evidence_query = f"{topic} {evidence}".strip()
    return {
        "feishu_public_knowledge": dedupe(
            [
                f"site:docs.feishu.cn {base}",
                f"site:docs.feishu.cn {base} 案例",
                f"site:docs.feishu.cn {base} SOP",
                f"site:docs.feishu.cn {base} 2026 OR 2025",
                f"site:docs.feishu.cn {evidence_query}",
            ]
        ),
        "official_sources": dedupe(
            [
                f"{context} 官方 文档",
                f"{base} 官方 帮助中心",
                f"{base} 开放平台 文档",
                f"site:open.feishu.cn {base}",
                f"site:feishu.cn {base} 帮助中心",
            ]
        ),
        "industry_cases": dedupe(
            [
                f"{base} 行业报告 2026",
                f"{base} 案例 复盘",
                f"{base} 最佳实践 SOP",
                f"{base} 趋势 2025 2026",
            ]
        ),
        "tavily_optional": dedupe(
            [
                context,
                f"{base} 最佳实践 案例 教程",
                evidence_query,
            ]
        ),
    }


def build_plan(payload: dict[str, Any], manual_urls: list[str], max_tasks: int) -> dict[str, Any]:
    planned_tasks: list[dict[str, Any]] = []
    for task in payload.get("tasks", [])[:max_tasks]:
        if not isinstance(task, dict):
            continue
        topic = compact(task.get("topic"))
        if not topic:
            continue
        question = compact(task.get("research_question"))
        evidence = compact(task.get("supporting_evidence"))
        queries = build_queries(topic, question, evidence)
        planned_tasks.append(
            {
                "task_id": compact(task.get("task_id")) or f"task-{len(planned_tasks) + 1:03d}",
                "topic": topic,
                "source": compact(task.get("source")),
                "blank_type": compact(task.get("blank_type")),
                "priority": compact(task.get("priority")),
                "research_question": question,
                "supporting_evidence": task.get("supporting_evidence", []),
                "source_queries": queries,
                "manual_urls": manual_urls,
                "draft_requirements": [
                    "草稿必须先使用 docs.feishu.cn 查询结果搭骨架。",
                    "没有 Tavily API 额度时跳过 tavily_optional，不阻塞流程。",
                    "每条关键判断必须能回指到主来源、官方依据或行业补充。",
                    "待确认草稿末尾必须包含：主来源、官方依据、行业与案例补充、手工来源、未覆盖问题。",
                    "禁止直接写正式知识库；只能写 research 待确认区。",
                ],
            }
        )
    return {
        "generated_at": datetime.now().astimezone().isoformat(timespec="seconds"),
        "source_strategy_version": 1,
        "task_count": len(planned_tasks),
        "source_tiers": SOURCE_TIERS,
        "scoring_dimensions": SCORING_DIMENSIONS,
        "tasks": planned_tasks,
    }


def render_markdown(plan: dict[str, Any]) -> str:
    lines = [
        "# P1-E 资料来源计划",
        "",
        f"- 生成时间：{plan['generated_at']}",
        f"- 任务数量：{plan['task_count']}",
        "- 搜索原则：飞书公共知识库优先，官方信息补边界，行业资料补案例，Tavily 仅作可选加速。",
        "",
        "## 来源优先级",
        "",
    ]
    for tier in plan["source_tiers"]:
        lines.append(f"{tier['priority'] + 1}. {tier['label']}：{tier['role']}（{tier['backend']}）")
    lines.extend(["", "## 打分维度", ""])
    for item in plan["scoring_dimensions"]:
        lines.append(f"- {item}")
    lines.append("")
    for task in plan["tasks"]:
        lines.extend(
            [
                f"## {task['task_id']}｜{task['topic']}",
                "",
                f"- 来源：{task['source']}",
                f"- 空白类型：{task['blank_type']}",
                f"- 优先级：{task['priority']}",
                f"- 研究问题：{task['research_question']}",
                "",
                "### 查询模板",
                "",
            ]
        )
        for tier in plan["source_tiers"]:
            queries = task.get("source_queries", {}).get(tier["tier"], [])
            if tier["tier"] == "manual_urls":
                queries = task.get("manual_urls", [])
            if not queries:
                continue
            lines.append(f"#### {tier['label']}")
            for query in queries:
                lines.append(f"- `{query}`")
            lines.append("")
        lines.extend(["### 待确认草稿硬约束", ""])
        for requirement in task["draft_requirements"]:
            lines.append(f"- {requirement}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"

def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv or sys.argv[1:])
    payload = load_tasks(args.tasks_json)
    plan = build_plan(payload, args.manual_url, args.max_tasks)
    json_text = json.dumps(plan, ensure_ascii=False, indent=2)
    markdown = render_markdown(plan)
    if args.json_out:
        args.json_out.write_text(json_text + "\n", encoding="utf-8")
    if args.markdown_out:
        args.markdown_out.write_text(markdown, encoding="utf-8")
    print(json_text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
